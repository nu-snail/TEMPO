"""Diagnostic: trace how many claims flow through each tier of verification.

Uses the reward_details from the actual training run plus the cached search
entries to reconstruct the exact Tier 1 → Tier 2 flow.
"""
import json, sys, os
from pathlib import Path
from collections import Counter

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
os.chdir(str(ROOT))

from dotenv import load_dotenv
load_dotenv(ROOT / ".env")

from full_experiment.llm import OpenRouterClient
from full_experiment.prompts import CATEGORIZE_PROMPT, LLM_DATE_CHECK_PROMPT, CONFIDENT_LEVELS
from full_experiment.schemas import CategorizationResult, DateVerifyResult, parse_json_array
from full_experiment.reward_pipeline import _CLAIM_CHUNK_SIZE, _MAX_TOKENS_PER_CHUNK

# We'll load real claims from the search_cache keys to simulate real claims
cache_path = ROOT / "runtime" / "cache" / "search_cache.json"
with open(cache_path) as f:
    cache = json.load(f)

stock_claims = []
for key in cache:
    if key.startswith("2025-03-31::"):
        claim_text = key.split("::", 1)[1]
        stock_claims.append(claim_text)

print(f"Total stock claims in search cache: {len(stock_claims)}")
print(f"(These are claims that were sent to Sonar at some point)")
print()

# These are the SEARCH QUERIES, not the original claim text.
# The search_query is generated by the categorizer.
# Let's look at the LLM Date Check prompt to understand what it expects.
# The key question: what categories are assigned, and what confidence does Tier 1 return?

# Let's take a sample of 60 claims (roughly matching one group's dedup count)
# and run them through categorization + Tier 1 to see the flow.
import random
random.seed(42)
sample = random.sample(stock_claims, min(60, len(stock_claims)))

print(f"Sampled {len(sample)} claims for diagnostic")
print()

client = OpenRouterClient(api_key=os.environ["OPENROUTER_API_KEY"])
judge_model = "google/gemini-2.5-flash-lite"
cutoff_date = "2025-03-31"

# Step 1: Categorize
print("=" * 60)
print("STEP 1: CATEGORIZATION")
print("=" * 60)
cat_results: dict[int, CategorizationResult] = {}
for start in range(0, len(sample), _CLAIM_CHUNK_SIZE):
    chunk = sample[start : start + _CLAIM_CHUNK_SIZE]
    payload = [{"index": start + j, "claim": c, "source": "B"} for j, c in enumerate(chunk)]
    prompt = CATEGORIZE_PROMPT.format(claims_json=json.dumps(payload, ensure_ascii=False, indent=2))
    text, _ = client.call_text(judge_model, prompt, temperature=0.0, max_tokens=_MAX_TOKENS_PER_CHUNK)
    for row in parse_json_array(text, CategorizationResult):
        cat_results[row.index] = row

cat_counts = Counter(r.category for r in cat_results.values())
print(f"Categorized {len(cat_results)}/{len(sample)} claims")
print(f"Category distribution: {dict(sorted(cat_counts.items()))}")

direct_leak = sum(1 for r in cat_results.values() if r.category in {"A4", "A5"})
direct_safe = sum(1 for r in cat_results.values() if r.category in {"B1", "B2"})
needs_verify = len(cat_results) - direct_leak - direct_safe
uncategorized = len(sample) - len(cat_results)

print(f"  Direct leak (A4/A5): {direct_leak}")
print(f"  Direct safe (B1/B2): {direct_safe}")
print(f"  Needs verification:  {needs_verify} (these go to Tier 1 LLM date check)")
print(f"  Uncategorized (parse fail): {uncategorized} (default to A1 → verification)")
print()

# Step 2: Tier 1 LLM Date Check
to_verify_indices = [i for i in range(len(sample))
                     if cat_results.get(i) is None or cat_results[i].category not in {"A4", "A5", "B1", "B2"}]

print("=" * 60)
print(f"STEP 2: TIER 1 LLM DATE CHECK ({len(to_verify_indices)} claims)")
print("=" * 60)

class FakeClaim:
    def __init__(self, text):
        self.text = text

llm_results: dict[int, DateVerifyResult] = {}
for chunk_start in range(0, len(to_verify_indices), _CLAIM_CHUNK_SIZE):
    chunk_end = min(chunk_start + _CLAIM_CHUNK_SIZE, len(to_verify_indices))
    chunk_payload = [
        {"index": j - chunk_start,
         "claim": sample[to_verify_indices[j]],
         "category": cat_results[to_verify_indices[j]].category if to_verify_indices[j] in cat_results else "A1"}
        for j in range(chunk_start, chunk_end)
    ]
    chunk_prompt = LLM_DATE_CHECK_PROMPT.format(
        claims_json=json.dumps(chunk_payload, ensure_ascii=False, indent=2)
    )
    chunk_text, _ = client.call_text(judge_model, chunk_prompt, temperature=0.0, max_tokens=_MAX_TOKENS_PER_CHUNK)
    for row in parse_json_array(chunk_text, DateVerifyResult):
        llm_results[chunk_start + row.index] = row

tier1_resolved = 0
tier1_leaked = 0
tier1_safe = 0
needs_search = 0
confidence_dist = Counter()

for j, claim_idx in enumerate(to_verify_indices):
    hit = llm_results.get(j)
    if hit is not None:
        confidence_dist[hit.confidence] += 1
        if hit.confidence in CONFIDENT_LEVELS and hit.event_date is not None:
            tier1_resolved += 1
            from full_experiment.reward_pipeline import _is_leaked_from_date
            if _is_leaked_from_date(hit.event_date, cutoff_date):
                tier1_leaked += 1
            else:
                tier1_safe += 1
        else:
            needs_search += 1
    else:
        needs_search += 1

print(f"Tier 1 parsed {len(llm_results)}/{len(to_verify_indices)} claims")
print(f"Confidence distribution: {dict(sorted(confidence_dist.items()))}")
print(f"  Tier 1 resolved (high/medium + has date): {tier1_resolved}")
print(f"    → Leaked: {tier1_leaked}")
print(f"    → Safe:   {tier1_safe}")
print(f"  Falls through to Tier 2 (Sonar): {needs_search}")
print()

tier2_pct = needs_search / max(len(sample), 1) * 100
print("=" * 60)
print("SUMMARY")
print("=" * 60)
print(f"Total claims: {len(sample)}")
print(f"  Direct categorization (A4/A5/B1/B2): {direct_leak + direct_safe} ({(direct_leak + direct_safe)/len(sample)*100:.0f}%)")
print(f"  Tier 1 resolved: {tier1_resolved} ({tier1_resolved/len(sample)*100:.0f}%)")
print(f"  Falls to Tier 2 (Sonar): {needs_search} ({tier2_pct:.0f}%)")
print()
print(f"Each Sonar call costs ~$0.005 in search fees alone.")
print(f"For {needs_search} Sonar calls: ~${needs_search * 0.005:.2f}")
print(f"Extrapolated to ~80 dedup claims/group: ~{int(80 * needs_search / len(sample))} Sonar calls → ~${80 * needs_search / len(sample) * 0.005:.2f}")
print(f"Extrapolated to 8 groups/step: ~{int(8 * 80 * needs_search / len(sample))} Sonar calls → ~${8 * 80 * needs_search / len(sample) * 0.005:.2f}")

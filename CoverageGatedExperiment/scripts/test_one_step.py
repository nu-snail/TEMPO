#!/usr/bin/env python3
"""
One-step end-to-end test of the new date-anchored leakage pipeline.

Runs ONE real training step (Tinker sampling + full reward pipeline) on a
small batch (batch_size=4, group_size=8) and logs everything in detail so we
can verify:
  1. source_date is being generated by Qwen (coverage rate)
  2. Plausibility verifier runs correctly (Stage 1 anchored detection)
  3. Leakage verdicts are consistent and precise
  4. Reward signal has enough variance to provide useful gradient signal

Usage:
  cd FullExperiment
  PYTHONPATH=src uv run python scripts/test_one_step.py 2>&1 | tee /tmp/test_one_step.log
"""

from __future__ import annotations

import json
import logging
import os
import sys
import time
from dataclasses import asdict
from pathlib import Path
from typing import Any

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
)
logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from cov_gated_experiment.config import load_config, load_env, require_api_keys
from cov_gated_experiment.data import load_train_instances, split_train_val
from cov_gated_experiment.lambda_schedule import cosine_anneal
from cov_gated_experiment.llm import OpenRouterClient
from cov_gated_experiment.prompts import build_generation_prompt
from cov_gated_experiment.reward_pipeline import RewardPipeline
from cov_gated_experiment.schemas import parse_completion

load_env(ROOT)

# ─── Reduced config for test ─────────────────────────────────────────────────
TEST_BATCH_SIZE  = 4   # instances per step
TEST_GROUP_SIZE  = 8   # completions per instance (half of training's 16)
TEST_TEMPERATURE = 0.8
TEST_MAX_TOKENS  = 4096
TEST_TASKS       = ["stock"]
# Pick 2 hard (cutoff=2021-12-31), 1 medium, 1 easy to test across tiers
WANT_TIERS = {"hard": 2, "medium": 1, "easy": 1}

RULER = "=" * 80


def _tier(cutoff: str) -> str:
    if cutoff <= "2021-12-31":
        return "hard"
    if cutoff <= "2023-02-28":
        return "medium"
    return "easy"


def pick_instances(data_root: Path) -> list[Any]:
    all_instances = load_train_instances(data_root, TEST_TASKS)
    train_set, _ = split_train_val(all_instances, 0.05, 42)

    buckets: dict[str, list] = {"hard": [], "medium": [], "easy": []}
    for inst in train_set:
        buckets[_tier(inst.cutoff_date)].append(inst)

    import random
    rng = random.Random(123)
    chosen: list[Any] = []
    for tier, n in WANT_TIERS.items():
        pool = buckets[tier]
        rng.shuffle(pool)
        chosen.extend(pool[:n])

    logger.info("Selected %d instances: %s", len(chosen),
                [(i.instance_id, i.cutoff_date, _tier(i.cutoff_date)) for i in chosen])
    return chosen


def sample_group(inst: Any, sampling_client: Any, renderer: Any,
                 group_size: int, params: Any) -> list[str]:
    """Sample group_size completions for one instance."""
    system_prompt, user_prompt = build_generation_prompt(inst)
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user",   "content": user_prompt},
    ]
    model_input = renderer.build_generation_prompt(messages)
    future = sampling_client.sample(
        prompt=model_input, num_samples=group_size, sampling_params=params
    )
    sampled = future.result()
    from tinker_cookbook import renderers as ru
    completions: list[str] = []
    for seq in sampled.sequences:
        msg, _ = renderer.parse_response(seq.tokens)
        completions.append(ru.get_text_content(msg))
    return completions


def log_completion_detail(inst: Any, comp_idx: int, comp_text: str) -> dict[str, Any]:
    """Parse one completion and show source_date coverage."""
    parsed = parse_completion(inst.task, comp_text)
    if parsed is None:
        print(f"    [{comp_idx:>2}] PARSE FAIL")
        return {}

    evidence = parsed.get("evidence", [])
    total_ev = len(evidence)
    dated_ev = sum(1 for e in evidence if e.get("source_date"))
    print(f"    [{comp_idx:>2}] evidence={total_ev}  source_date coverage={dated_ev}/{total_ev}", end="")

    missing = [e for e in evidence if not e.get("source_date")]
    if missing:
        print(f"  ← MISSING DATES on {len(missing)} items: {[e['fact'][:50] for e in missing[:2]]}")
    else:
        print()

    # Show first 5 evidence items with dates
    for ev in evidence[:5]:
        sd = ev.get("source_date", "—")
        print(f"         [{sd}]  {ev['fact'][:90]}")
    if len(evidence) > 5:
        print(f"         ... and {len(evidence)-5} more evidence items")

    return parsed


def log_claim_verdicts(claim_detail: dict[str, Any], cutoff: str) -> None:
    """Print claim-level leakage detection results with stage annotation."""
    claims = claim_detail.get("claims", [])
    if not claims:
        print("    (no claims)")
        return

    anchored = [c for c in claims if c.get("leak_method") == "anchored"]
    inferred = [c for c in claims if c.get("leak_method") == "inferred"]
    unknown  = [c for c in claims if c.get("leak_method") not in ("anchored", "inferred")]

    n_leaked = sum(1 for c in claims if c.get("leak_verdict") == "leaked")
    print(f"    Claims: {len(claims)} total  |  Stage-1 anchored: {len(anchored)}  Stage-2 inferred: {len(inferred)}  unknown: {len(unknown)}")
    print(f"    Leaked: {n_leaked}/{len(claims)}")

    # Show all claims with verdicts
    for c in claims:
        stage = "A" if c.get("leak_method") == "anchored" else ("B" if c.get("leak_method") == "inferred" else "?")
        verdict = c.get("leak_verdict", "?")
        ev_date = c.get("leak_event_date", "?")
        plausible = c.get("leak_plausible")
        flag = ""
        if verdict == "leaked":
            flag = " <<< LEAKED"
        if plausible is False:
            flag += "  [DATE CORRECTED]"
        print(f"    [{stage}] {verdict:>10} [{ev_date:>12}]  {c['text'][:80]}{flag}")


def print_group_reward_summary(
    rewards: list[Any],
    advantages: list[float],
    inst_id: str,
    cutoff: str,
    tier: str,
) -> dict[str, Any]:
    """Print per-completion reward table and signal quality metrics."""
    import numpy as np

    print(f"\n  ─── Reward Summary: {inst_id} (cutoff={cutoff}, tier={tier}) ───")
    print(f"  {'#':>3}  {'r_leak_exp':>10}  {'num_leaked':>10}  {'n_claims':>8}  "
          f"{'r_perf':>7}  {'r_valid':>7}  {'coverage':>8}  {'advantage':>10}  {'status'}")
    print(f"  {'-'*95}")

    r_leak_vals = []
    adv_vals = []
    for i, (r, adv) in enumerate(zip(rewards, advantages)):
        if not r.parse_success:
            print(f"  {i:>3}  {'—':>10}  {'—':>10}  {'—':>8}  {'—':>7}  {'—':>7}  {'—':>8}  {adv:>+10.4f}  PARSE_FAIL")
            continue
        import math
        r_leak_exp = math.exp(-0.5 * r.num_leaked)
        r_leak_vals.append(r_leak_exp)
        adv_vals.append(adv)
        print(f"  {i:>3}  {r_leak_exp:>10.4f}  {r.num_leaked:>10}  {r.num_claims:>8}  "
              f"{r.r_performance:>7.3f}  {r.r_valid:>7.3f}  {r.coverage:>8.3f}  {adv:>+10.4f}")

    if r_leak_vals:
        arr = np.array(r_leak_vals)
        adv_arr = np.array(adv_vals)
        print(f"\n  Signal quality:")
        print(f"    r_leak_exp  mean={arr.mean():.4f}  std={arr.std():.4f}  min={arr.min():.4f}  max={arr.max():.4f}")
        print(f"    advantages  mean={adv_arr.mean():+.4f}  std={adv_arr.std():.4f}  abs_mean={np.abs(adv_arr).mean():.4f}")
        zero_variance = arr.std() < 0.01
        print(f"    Zero-variance group? {'YES — no leakage gradient!' if zero_variance else 'NO — signal present ✓'}")
        return {
            "instance_id": inst_id, "cutoff": cutoff, "tier": tier,
            "r_leak_std": float(arr.std()), "r_leak_mean": float(arr.mean()),
            "adv_std": float(adv_arr.std()), "zero_variance": zero_variance,
        }
    return {"instance_id": inst_id, "zero_variance": True}


def main() -> None:
    import tinker
    from tinker import types as tinker_types
    from tinker_cookbook import model_info, renderers
    from tinker_cookbook.tokenizer_utils import get_tokenizer

    cfg = load_config(ROOT / "configs/train.yaml")
    cfg.train_tasks = "stock"

    openrouter_key, tinker_key = require_api_keys()
    os.environ["TINKER_API_KEY"] = tinker_key
    judge_client = OpenRouterClient(openrouter_key)
    reward_pipe = RewardPipeline(cfg, judge_client)

    # Tinker setup
    svc = tinker.ServiceClient()
    tc = svc.create_lora_training_client(base_model=cfg.model_name, rank=cfg.lora_rank)

    tok = get_tokenizer(cfg.model_name)
    rname = model_info.get_recommended_renderer_name(cfg.model_name)
    renderer = renderers.get_renderer(rname, tok)

    sampling_params = tinker_types.SamplingParams(
        max_tokens=TEST_MAX_TOKENS,
        temperature=TEST_TEMPERATURE,
        stop=renderer.get_stop_sequences(),
    )

    data_root = ROOT / cfg.data_root
    batch = pick_instances(data_root)

    print(f"\n{RULER}")
    print(f"  ONE-STEP TEST: date-anchored leakage pipeline")
    print(f"  batch_size={TEST_BATCH_SIZE}  group_size={TEST_GROUP_SIZE}")
    print(f"  judge_model={cfg.judge_model}")
    print(RULER)

    # ── Step 1: Parallel Tinker sampling (mirrors train.py) ──────────────────
    print("\n[Step 1] Sampling completions via Tinker (parallel)...")
    t0 = time.time()
    sampling_client = tc.save_weights_and_get_sampling_client()

    from concurrent.futures import ThreadPoolExecutor
    pending = []
    for inst in batch:
        system_p, user_p = build_generation_prompt(inst)
        messages = [{"role": "system", "content": system_p}, {"role": "user", "content": user_p}]
        model_input = renderer.build_generation_prompt(messages)
        future = sampling_client.sample(
            prompt=model_input,
            num_samples=TEST_GROUP_SIZE,
            sampling_params=sampling_params,
        )
        pending.append((inst, model_input, future))

    groups: list[tuple[Any, list[str]]] = []
    from tinker_cookbook import renderers as ru
    for inst, model_input, future in pending:
        sampled = future.result()
        completions = []
        for seq in sampled.sequences:
            msg, _ = renderer.parse_response(seq.tokens)
            completions.append(ru.get_text_content(msg))
        groups.append((inst, completions))
        logger.info("Received %d completions for %s", len(completions), inst.instance_id)

    t_sample = time.time() - t0
    logger.info("Sampling done in %.1fs", t_sample)

    # ── Step 2: Score each group + detailed logging ──────────────────────────
    print(f"\n[Step 2] Running reward pipeline...")

    all_rewards: list[list[Any]] = []
    all_details: list[dict[str, Any]] = []
    batch_summaries: list[dict] = []

    for inst, completions in groups:
        tier = _tier(inst.cutoff_date)
        print(f"\n{RULER}")
        print(f"  INSTANCE: {inst.instance_id}  cutoff={inst.cutoff_date}  tier={tier}")
        print(f"  Companies: {inst.raw.get('companies', [])}")
        print(RULER)

        # ── 2a: Show all completions (parsed, source_date coverage) ─────────
        print("\n  ── Evidence + source_date per completion ──")
        for ci, comp_text in enumerate(completions):
            log_completion_detail(inst, ci, comp_text)

        # ── 2b: Run the reward pipeline ──────────────────────────────────────
        print("\n  ── Running reward pipeline (skip_hallucination=True for training) ──")
        t_reward_start = time.time()
        rewards, detail = reward_pipe.score_group(
            completions, inst, skip_hallucination=True
        )
        t_reward = time.time() - t_reward_start
        print(f"  Reward pipeline done in {t_reward:.1f}s")

        all_rewards.append(rewards)
        all_details.append(detail)

        # ── 2c: Show claim-level leakage detail ─────────────────────────────
        print("\n  ── Claim-level leakage detection ──")
        log_claim_verdicts(detail, inst.cutoff_date)

        # ── 2d: Check consistency within evidence claims ─────────────────────
        # Find claims from same "category" (by looking for year-pattern in text)
        claims = detail.get("claims", [])
        annual_claims = [
            c for c in claims
            if any(pat in c["text"].lower() for pat in
                   ["annual", "full year", "fy20", "fy21", "fy22", "fy23",
                    "2021 revenue", "2022 revenue", "2023 revenue",
                    "full-year", "yearly"])
        ]
        if annual_claims:
            verdicts = [c.get("leak_verdict") for c in annual_claims]
            consistent = len(set(verdicts)) == 1
            print(f"\n  ── Annual-financial claim consistency ──")
            for c in annual_claims:
                print(f"    [{c.get('leak_method','?')}] {c.get('leak_verdict','?'):>10} "
                      f"[{c.get('leak_event_date','?'):>12}]  {c['text'][:80]}")
            print(f"    Consistent? {'YES ✓' if consistent else 'INCONSISTENT ← problem!'}")

        # ── 2e: Advantages ───────────────────────────────────────────────────
        batch_r_leak = sum(
            __import__('math').exp(-0.5 * r.num_leaked)
            for r in rewards if r.parse_success
        ) / max(sum(1 for r in rewards if r.parse_success), 1)

        w_leak = cosine_anneal(0, 75, cfg.w_leak_start, cfg.w_leak_end)
        advantages, adv_diag = reward_pipe.compute_advantages(rewards, w_leak, batch_r_leak)

        summary = print_group_reward_summary(
            rewards, advantages, inst.instance_id, inst.cutoff_date, tier
        )
        summary["t_reward_s"] = round(t_reward, 1)
        summary["r_leak_std_diag"] = adv_diag.get("r_leak_std", 0.0)
        batch_summaries.append(summary)

    # ── Step 3: Batch-level summary ──────────────────────────────────────────
    print(f"\n{RULER}")
    print(f"  BATCH SUMMARY")
    print(RULER)
    print(f"\n  {'INSTANCE':>20}  {'TIER':>6}  {'CUTOFF':>12}  "
          f"{'r_leak_std':>10}  {'adv_std':>8}  {'SIGNAL':>10}  {'t_reward'}")
    print(f"  {'-'*90}")
    for s in batch_summaries:
        signal = "FLAT" if s.get("zero_variance") else "OK"
        print(f"  {s.get('instance_id','?'):>20}  {s.get('tier','?'):>6}  "
              f"{s.get('cutoff','?'):>12}  {s.get('r_leak_std',0):>10.4f}  "
              f"{s.get('adv_std',0):>8.4f}  {signal:>10}  {s.get('t_reward_s','?')}s")

    n_signal = sum(1 for s in batch_summaries if not s.get("zero_variance"))
    print(f"\n  Groups with non-zero leakage signal: {n_signal}/{len(batch_summaries)}")
    print(f"  Total sampling time: {t_sample:.1f}s")
    print(f"\n[Done]")

    # ── Save full details to file ────────────────────────────────────────────
    out_path = Path("/tmp/test_one_step_detail.json")
    with open(out_path, "w") as f:
        json.dump(
            {
                "batch_summaries": batch_summaries,
                "claim_details": all_details,
            },
            f, indent=2, default=str,
        )
    print(f"  Full claim detail saved to {out_path}")


if __name__ == "__main__":
    main()
